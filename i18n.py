def translate(value, language="id"):
    text = str(value)
    if language != "en":
        return text
    # Long phrases first prevent a shorter word from breaking a full label.
    for source, target in sorted(EN.items(), key=lambda item: len(item[0]), reverse=True):
        text = text.replace(source, target)
    return text
